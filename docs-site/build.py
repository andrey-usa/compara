#!/usr/bin/env python3
"""Write the docs site's generated pages from their sources, then `mdbook build`.

    python3 docs-site/build.py [path/to/compara]

The site never drifts from what it shows, because these pages are written
from one source each on every Pages build:

    index.md   README.md without the sections below
    cloud.md   README.md's "Cloud and containers" section
    speed.md   README.md's "Speed" and "Engines" sections
    cli.md     `compara --help` of the binary given (default
               target/release/compara)

examples.md is written by hand and pulls its files in with mdBook's
`{{#include}}`. Relative links to a file in the repository point at it on
GitHub; links to a README section point at the page that holds it.
Standard library only.
"""
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "docs-site" / "src"
BLOB = "https://github.com/andrey-usa/compara/blob/main/"
LINK = re.compile(r"\]\((?!https?:|mailto:)([^)\s]+)\)")
NOTE = "<!-- Generated by docs-site/build.py from {src}. Edit the source, not this page. -->\n\n"
# Page -> (title, the README sections it holds, in order).
PAGES = {
    "cloud.md": ("Cloud and containers", ["Cloud and containers"]),
    "speed.md": ("Speed, engines and formats", ["Speed", "Engines"]),
}


def sections(readme):
    """README as [(heading or None for the part before the first `## `, text)]."""
    parts = re.split(r"(?m)^(?=## )", readme)
    out = []
    for part in parts:
        m = re.match(r"## (.+)\n", part)
        out.append((m.group(1).strip() if m else None, part))
    return out


def anchor(heading):
    return re.sub(r"[^a-z0-9 -]", "", heading.lower()).replace(" ", "-")


def relink(text, anchors):
    """Relative links: a moved README section -> its page, a file -> GitHub."""

    def fix(m):
        target = m.group(1)
        if target.startswith("#"):
            page = anchors.get(target[1:])
            return f"]({page}{target})" if page else m.group(0)
        path, _, frag = target.partition("#")
        path = path[2:] if path.startswith("./") else path
        return f"]({BLOB}{path}{'#' + frag if frag else ''})"

    return LINK.sub(fix, text)


def write(name, source, body):
    (SRC / name).write_text(NOTE.format(src=source) + body, encoding="utf-8")


def main():
    binary = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else ROOT / "target" / "release" / "compara")
    parts = sections((ROOT / "README.md").read_text(encoding="utf-8"))
    headings = {h for h, _ in parts if h}
    taken, anchors = set(), {}
    for page, (_, wanted) in PAGES.items():
        missing = [w for w in wanted if w not in headings]
        if missing:
            sys.exit(f"docs-site/build.py: README.md has no section {missing}; update PAGES")
        taken.update(wanted)
        anchors.update({anchor(w): page for w in wanted})
    anchors.update({anchor(h): "index.md" for h in headings - taken})
    for page, (title, wanted) in PAGES.items():
        body = "".join(text for h, text in parts if h in wanted)
        write(page, "README.md", f"# {title}\n\n" + relink(body, anchors))
    index = "".join(text for h, text in parts if h not in taken)
    write("index.md", "README.md", relink(index, anchors))
    help_text = subprocess.run([str(binary), "--help"], check=True, capture_output=True, text=True).stdout
    write(
        "cli.md",
        "`compara --help`",
        "# CLI reference (`compara --help`)\n\nThe output of `compara --help` from the build this site was made with:\n\n"
        f"```text\n{help_text.rstrip()}\n```\n",
    )
    print(f"docs-site: wrote {len(PAGES) + 2} pages")


if __name__ == "__main__":
    main()
